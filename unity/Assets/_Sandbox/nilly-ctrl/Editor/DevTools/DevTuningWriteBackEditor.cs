using System;
using System.Collections.Generic;
using System.Text;
using HoldTheHill.Features.Enemies;
using UnityEditor;
using UnityEngine;

namespace HoldTheHill.Sandbox.NillyCtrl
{
    /// <summary>
    /// The Editor half of the tuning panel's "copy to data asset": writes the changed numbers into
    /// the prefab the live object came from, through <see cref="SerializedObject"/>, so the change
    /// is saved and survives leaving Play mode.
    /// </summary>
    /// <remarks>
    /// Tower numbers (range, fire interval, weapon fields) live on the tower prefab, not on
    /// <c>GrayboxTowerData</c>, so that is where they are written. Tower prefabs are made only when
    /// missing, so the values stick. Enemy, boss and pickup prefabs are rebuilt by their builders,
    /// so a value written there is overwritten on the next build; the message says so.
    /// </remarks>
    [InitializeOnLoad]
    public static class DevTuningWriteBackEditor
    {
        static DevTuningWriteBackEditor()
        {
            DevTuningWriteBack.Handler = Apply;
        }

        private static string Apply(GameObject instance, GameObject prefabHint, IList<DevTunedChange> changes)
        {
            GameObject source = instance != null ? PrefabUtility.GetCorrespondingObjectFromSource(instance) : null;
            string path = source != null ? AssetDatabase.GetAssetPath(source) : null;
            if (string.IsNullOrEmpty(path) && prefabHint != null)
            {
                source = prefabHint;
                path = AssetDatabase.GetAssetPath(prefabHint);
            }

            if (source == null || string.IsNullOrEmpty(path))
            {
                return "No prefab asset found for '" + (instance != null ? instance.name : "?") + "'. Use Copy as text.";
            }

            int written = 0;
            var skipped = new StringBuilder();
            foreach (DevTunedChange change in changes)
            {
                Component[] candidates = source.GetComponents(change.ComponentType);
                if (change.ComponentIndex >= candidates.Length)
                {
                    skipped.Append(' ').Append(change.ComponentType.Name).Append('.').Append(change.FieldName);
                    continue;
                }

                Component target = candidates[change.ComponentIndex];
                var serialized = new SerializedObject(target);
                SerializedProperty property = serialized.FindProperty(change.FieldName);
                if (property == null || !SetValue(property, change))
                {
                    skipped.Append(' ').Append(change.ComponentType.Name).Append('.').Append(change.FieldName);
                    continue;
                }

                serialized.ApplyModifiedPropertiesWithoutUndo();
                EditorUtility.SetDirty(target);
                written++;
            }

            if (written > 0) AssetDatabase.SaveAssets();

            string message = "Wrote " + written + " value" + (written == 1 ? string.Empty : "s") + " to " + path + ".";
            if (skipped.Length > 0) message += " Not found on the prefab:" + skipped + ".";
            if (instance != null && instance.GetComponent<EnemyHealth>() != null)
            {
                message += " Enemy prefabs are regenerated by their builder, so rebuilding will overwrite this; change the builder too.";
            }

            return message;
        }

        private static bool SetValue(SerializedProperty property, DevTunedChange change)
        {
            switch (property.propertyType)
            {
                case SerializedPropertyType.Float:
                    property.floatValue = Convert.ToSingle(change.Value);
                    return true;
                case SerializedPropertyType.Integer:
                    property.intValue = Convert.ToInt32(change.Value);
                    return true;
                case SerializedPropertyType.Boolean:
                    property.boolValue = Convert.ToBoolean(change.Value);
                    return true;
                case SerializedPropertyType.Enum:
                    int index = Array.IndexOf(property.enumNames, change.Value.ToString());
                    if (index < 0) return false;
                    property.enumValueIndex = index;
                    return true;
                default:
                    return false;
            }
        }
    }
}
