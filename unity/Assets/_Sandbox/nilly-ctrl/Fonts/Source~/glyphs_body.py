# ---------------------------------------------------------------- accented letters
# A two-row mark sits in the empty rows above a lowercase letter, or on two extra rows above a
# capital. Each mark comes five wide and, for i, three wide.
MARKS = {
    "̀": ([".#...", "..#.."], ["#..", ".#."]),   # grave
    "́": (["...#.", "..#.."], ["..#", ".#."]),   # acute
    "̂": (["..#..", ".#.#."], [".#.", "#.#"]),   # circumflex
    "̃": ([".##.#", "#.##."], None),             # tilde
    "̈": ([".#.#.", "....."], ["#.#", "..."]),   # diaeresis
}
ACCENTED = {
    "̀": "AEIOUaeiou",
    "́": "AEIOUYaeiouy",
    "̂": "AEIOUaeiou",
    "̃": "ANOano",
    "̈": "AEIOUaeiouy",
}
CEDILLA = ["..#.", ".#.."]
DOTLESS_I = [".", ".", "#", "#", "#", "#", "#"]


def _centre(rows, width):
    extra = width - len(rows[0])
    left = extra // 2
    return ["." * left + r + "." * (extra - left) for r in rows]


def _accents():
    out, top = {}, {}
    letters = dict(CAPS)
    letters.update(LOWER)
    for mark, bases in ACCENTED.items():
        wide, narrow = MARKS[mark]
        for base in bases:
            rows = DOTLESS_I if base == "i" else letters[base]
            m = narrow if len(rows[0]) < 5 else wide
            rows = _centre(rows, len(m[0]))
            ch = unicodedata.normalize("NFC", base + mark)
            if base.islower():
                out[ch] = m + rows[2:]
            else:
                out[ch] = m + rows
                top[ch] = 9
    for base in "Cc":
        rows = letters[base]
        out[unicodedata.normalize("NFC", base + "̧")] = rows + _centre(CEDILLA, len(rows[0]))
    return out, top


_ACC, _ACC_TOP = _accents()
TOP.update(_ACC_TOP)

ALL = {}
for _part in (CAPS, LOWER, PUNCT, SYMBOLS, _ACC):
    ALL.update(_part)

# Characters that type as something the font already has.
ALIASES = {"‘": "'", "’": "'", "“": '"', "”": '"', "–": "-", "·": "•"}

for _ch, _rows in list(ALL.items()) + list(BOLD.items()):
    assert len({len(r) for r in _rows}) == 1, f"body glyph {_ch!r} has uneven rows"
    assert len(_rows) in (7, 9), f"body glyph {_ch!r} has {len(_rows)} rows"
