_SCRIPT_LEAN = 3      # rows per pixel of lean
_SCRIPT_EXTRA = 3     # columns the lean adds to every glyph


def _lean(rows, cap):
    out = []
    for i, r in enumerate(rows):
        shift = (cap - 1 - i) // _SCRIPT_LEAN + 1
        out.append("." * shift + r + "." * (_SCRIPT_EXTRA - shift))
    return out


