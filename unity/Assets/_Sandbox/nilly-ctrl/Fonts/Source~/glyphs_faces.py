"""Thirteen more alphabets, each with its own character.

  SERIF      5-7 x 8, one-pixel strokes with foot serifs; capitals and lowercase. Lore and menu text.
  ROUND      6 x 8, two-pixel strokes and soft corners; capitals and lowercase. Friendly menus.
  TECH       5 x 7, squared-off; capitals only. Sci-fi readouts.
  GOTHIC     6 x 9, heavy stems with pointed feet; capitals only. Bosses and spooky titles.
  CONDENSED  3 x 9, tall and narrow; capitals only. Tight HUD space.
  CHISEL     5 x 8, straight cuts and diamonds, no curves; capitals only.
  STENCIL    the display alphabet with breaks cut by hand into every letter; capitals only.
  SLAB       7 x 9, two-pixel stems between slab serifs; capitals only. Wanted posters, saloon signs.
  BUBBLE     8 x 9, three-pixel strokes; capitals only. Loud, soft titles.
  WIDE       7 x 5, low and stretched; small capitals for lowercase. Arcade and racing readouts.
  DECO       5 x 10, tall and thin with a high waist; capitals only. Marquees and posters.
  RUNIC      5 x 8, straight cuts with slanted bars; capitals only. Carved stones.
  SCRIPT     a leaning casual hand; capitals and lowercase. Notes and signatures.
Tech, Gothic, Condensed, Chisel, Slab and Bubble also have lowercase (see the lowercase section).

A glyph is a list of rows. A face's capitals are `cap` rows tall; a glyph with two more rows than
that hangs below the baseline. FACES at the bottom is what build_pixel_fonts.py reads.
"""
import glyphs_body
import glyphs_display
import glyphs_tiny

BODY_PUNCT = "+-.,%!?/:()' "


def _from_body(rows_above):
    """The body alphabet's punctuation, moved down to sit on a taller face's baseline."""
    out = {}
    for ch in BODY_PUNCT:
        rows = glyphs_body.ALL[ch]
        out[ch] = ["." * len(rows[0])] * rows_above + rows
    cross = glyphs_body.ALL["x"]
    out["×"] = ["." * 5] * rows_above + cross
    return out


