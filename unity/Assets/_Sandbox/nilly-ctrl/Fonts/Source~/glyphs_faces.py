def _pad_top(rows, n):
    return ["." * len(rows[0])] * n + rows


def _bolder(rows):
    """Every pixel also fills the one to its right."""
    out = []
    for r in rows:
        r = r + "."
        out.append("".join("#" if r[x] == "#" or (x > 0 and r[x - 1] == "#") else "." for x in range(len(r))))
    return out


def _squared(rows):
    """Fills the single missing pixel at each rounded outer corner, for a blockier letter."""
    h, w = len(rows), len(rows[0])
    on = lambda x, y: 0 <= y < h and 0 <= x < w and rows[y][x] == "#"

    def clear(x, y, dx, dy):
        """True if nothing is inked from here to the edge of the glyph, walking one way."""
        x, y = x + dx, y + dy
        while 0 <= x < w and 0 <= y < h:
            if rows[y][x] == "#":
                return False
            x, y = x + dx, y + dy
        return True

    out = [list(r) for r in rows]
    for y in range(h):
        for x in range(w):
            if rows[y][x] == "#":
                continue
            for dx, dy in ((1, 1), (1, -1), (-1, 1), (-1, -1)):
                # ink beside and above/below and diagonally, open sky on the other two sides
                if on(x + dx, y) and on(x, y + dy) and on(x + dx, y + dy) and clear(x, y, -dx, 0) and clear(x, y, 0, -dy):
                    out[y][x] = "#"
    return ["".join(r) for r in out]


