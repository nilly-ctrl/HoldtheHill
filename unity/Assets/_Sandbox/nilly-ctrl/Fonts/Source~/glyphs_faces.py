# ---------------------------------------------------------------- Stencil
def _stencil():
    """The display alphabet with a two-pixel bridge cut through the bars that close a shape."""
    out = {}
    for ch, rows in glyphs_display.GLYPHS.items():
        grid = [list(r) for r in rows]
        w = len(grid[0])
        if ch in "ABDOPQR0689" and w >= 8:
            mid = w // 2 - 1
            for y in range(len(grid)):
                # a bar is a filled row over (or under) an empty counter: cut it, leave stems alone
                above = y > 0 and grid[y - 1][mid] == "."
                below = y < len(grid) - 1 and grid[y + 1][mid] == "."
                bar = all(c == "#" for c in rows[y][1:w - 1])
                if bar and (above or below or y in (0, len(grid) - 1)):
                    grid[y][mid] = grid[y][mid + 1] = "."
        out[ch] = ["".join(r) for r in grid]
    return out


STENCIL = _stencil()

