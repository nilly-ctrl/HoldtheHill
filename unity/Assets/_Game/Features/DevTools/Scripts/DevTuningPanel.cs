#if UNITY_EDITOR || DEVELOPMENT_BUILD
using System;
using System.Collections.Generic;
using HoldTheHill.Features.Enemies;
using HoldTheHill.Features.Towers;
using UnityEngine;
using UnityEngine.InputSystem;

namespace HoldTheHill.Features.DevTools
{
    /// <summary>
    /// A panel for changing the selected tower's or an enemy's numbers while the game runs, with
    /// "copy to data asset" to keep them after Play mode (Editor only). F2 shows or hides it.
    /// </summary>
    /// <remarks>
    /// Tower mode follows the tower selected in the game. Enemy mode shows the enemy picked with F3
    /// (the one nearest the mouse). A number change affects that one object; "apply to all" copies
    /// the changed numbers onto every object with the same name.
    ///
    /// Enemy, boss and pickup prefabs are regenerated by the editor builders on every build, so a
    /// value written to one of those prefabs is lost on the next rebuild. Use "copy as text" and
    /// change the builder for those.
    /// </remarks>
    [AddComponentMenu("Hold the Hill/DevTools/Dev Tuning Panel")]
    public class DevTuningPanel : MonoBehaviour
    {
        private const string ControlPrefix = "dev-tune-";

        private enum Mode
        {
            Tower,
            Enemy,
        }

        private Mode _mode = Mode.Tower;
        private TowerPlacer _placer;
        private GameObject _target;
        private List<DevTunedField> _fields = new List<DevTunedField>();
        private Vector2 _scroll;
        private string _status = "Select a tower, or press F3 over an enemy.";

        public static DevTuningPanel Instance { get; private set; }

        public static bool Visible { get; set; }

        [RuntimeInitializeOnLoadMethod(RuntimeInitializeLoadType.SubsystemRegistration)]
        private static void ResetStatics()
        {
            Instance = null;
            Visible = false;
        }

        private void Awake()
        {
            if (Instance != null && Instance != this)
            {
                Destroy(this);
                return;
            }

            Instance = this;
        }

        private void OnDisable()
        {
            DevInput.Lock(this, false);
            if (Instance == this) Instance = null;
        }

        private void Update()
        {
            Keyboard keyboard = Keyboard.current;
            if (keyboard != null)
            {
                if (keyboard.f2Key.wasPressedThisFrame) Visible = !Visible;
                if (Visible && keyboard.f3Key.wasPressedThisFrame) PickEnemyUnderMouse();
            }

            if (!Visible)
            {
                DevInput.Lock(this, false);
                return;
            }

            if (_placer == null) _placer = FindAnyObjectByType<TowerPlacer>();

            if (_mode == Mode.Tower && _placer != null)
            {
                Tower selected = _placer.SelectedTower;
                GameObject selectedObject = selected != null ? selected.gameObject : null;
                if (selectedObject != _target) SetTarget(selectedObject);
            }
            else if (_target == null && _fields.Count > 0)
            {
                SetTarget(null);
            }
        }

        private void SetTarget(GameObject target)
        {
            _target = target;
            _fields = DevTuning.Collect(target);
            _scroll = Vector2.zero;
        }

        private void PickEnemyUnderMouse()
        {
            Camera camera = Camera.main;
            Mouse mouse = Mouse.current;
            if (camera == null || mouse == null) return;

            Vector3 world = camera.ScreenToWorldPoint(mouse.position.ReadValue());
            EnemyHealth best = null;
            float bestDistance = float.MaxValue;
            foreach (EnemyHealth enemy in FindObjectsByType<EnemyHealth>())
            {
                if (enemy.IsDead) continue;
                float d = Vector2.Distance(world, enemy.transform.position);
                if (d < bestDistance)
                {
                    best = enemy;
                    bestDistance = d;
                }
            }

            if (best == null)
            {
                _status = "No enemy on the field to pick.";
                return;
            }

            _mode = Mode.Enemy;
            SetTarget(best.gameObject);
            _status = "Picked " + best.name + ".";
        }

        private void OnGUI()
        {
            if (!Visible) return;

            DevGui.Ensure();
            GUI.depth = -950;

            float width = DevGui.FontSize * 30f;
            var rect = new Rect(Screen.width - width - 8f, 8f, width, Screen.height - 16f);
            DevGui.Occupy(rect);

            GUILayout.BeginArea(rect, DevGui.Panel);
            GUILayout.Label("Live tuning  (F2 hides, F3 picks the enemy under the mouse)", DevGui.Heading);

            GUILayout.BeginHorizontal();
            if (GUILayout.Toggle(_mode == Mode.Tower, "Tower", DevGui.Button) && _mode != Mode.Tower)
            {
                _mode = Mode.Tower;
                SetTarget(null);
            }

            if (GUILayout.Toggle(_mode == Mode.Enemy, "Enemy", DevGui.Button) && _mode != Mode.Enemy)
            {
                _mode = Mode.Enemy;
                SetTarget(null);
            }

            GUILayout.EndHorizontal();

            if (_target == null)
            {
                GUILayout.Label(_mode == Mode.Tower ? "No tower selected. Click one in the game." : "No enemy picked. Press F3 with the mouse over one.", DevGui.Label);
            }
            else
            {
                DrawTarget();
            }

            GUILayout.FlexibleSpace();
            GUILayout.Label(_status, DevGui.Label);
            GUILayout.EndArea();

            string focused = GUI.GetNameOfFocusedControl();
            DevInput.Lock(this, !string.IsNullOrEmpty(focused) && focused.StartsWith(ControlPrefix, StringComparison.Ordinal));
        }

        private void DrawTarget()
        {
            string title = _target.name;
            Tower tower = _target.GetComponent<Tower>();
            if (tower != null) title += "  (level " + tower.Level + ")";
            EnemyHealth health = _target.GetComponent<EnemyHealth>();
            if (health != null) title += "  (" + Mathf.CeilToInt(health.CurrentHealth) + " / " + Mathf.CeilToInt(health.MaxHealth) + " hp)";
            GUILayout.Label(title, DevGui.Heading);

            _scroll = GUILayout.BeginScrollView(_scroll, GUILayout.ExpandHeight(true));
            for (int i = 0; i < _fields.Count; i++) DrawField(_fields[i], i);
            if (_fields.Count == 0) GUILayout.Label("No tunable numbers found on this object.", DevGui.Label);
            GUILayout.EndScrollView();

            GUILayout.BeginHorizontal();
            if (GUILayout.Button("Reset", DevGui.Button)) ResetAll();
            if (GUILayout.Button("Apply to all '" + _target.name + "'", DevGui.Button)) ApplyToAll();
            GUILayout.EndHorizontal();

            GUILayout.BeginHorizontal();
            GUI.enabled = DevTuningWriteBack.Available;
            if (GUILayout.Button("Copy to data asset", DevGui.Button)) CopyToAsset();
            GUI.enabled = true;
            if (GUILayout.Button("Copy as text", DevGui.Button)) CopyAsText();
            GUILayout.EndHorizontal();

            if (health != null && GUILayout.Button("Heal to full", DevGui.Button)) health.Heal(health.MaxHealth);
        }

        private void DrawField(DevTunedField field, int index)
        {
            string control = ControlPrefix + index;
            GUILayout.BeginHorizontal();
            GUILayout.Label((field.Changed ? "<color=#ffd966>* " : string.Empty) + field.Label + (field.Changed ? "</color>" : string.Empty),
                DevGui.Label, GUILayout.Width(DevGui.FontSize * 14f));

            Type type = field.ValueType;
            if (type == typeof(bool))
            {
                bool value = (bool)field.Value;
                bool next = GUILayout.Toggle(value, value ? "on" : "off", DevGui.Toggle);
                if (next != value) field.Value = next;
            }
            else if (type.IsEnum)
            {
                if (GUILayout.Button(field.Value.ToString(), DevGui.Button)) field.Value = DevTuning.NextEnum(type, field.Value);
            }
            else
            {
                if (GUILayout.Button("-", DevGui.Button, GUILayout.Width(DevGui.Line))) Nudge(field, 0.9f);

                bool focused = GUI.GetNameOfFocusedControl() == control;
                if (!focused || field.Buffer == null) field.Buffer = DevTuning.Format(field.Value);

                GUI.SetNextControlName(control);
                string text = GUILayout.TextField(field.Buffer, DevGui.Field);
                if (text != field.Buffer)
                {
                    field.Buffer = text;
                    if (DevTuning.TryParse(field, text, out object parsed)) field.Value = parsed;
                }

                if (GUILayout.Button("+", DevGui.Button, GUILayout.Width(DevGui.Line))) Nudge(field, 1.1f);
            }

            GUILayout.EndHorizontal();
        }

        // 10% up or down; a whole number always moves by at least one.
        private static void Nudge(DevTunedField field, float factor)
        {
            if (field.ValueType == typeof(float))
            {
                field.Value = (float)field.Value * factor;
            }
            else if (field.ValueType == typeof(int))
            {
                int value = (int)field.Value;
                int next = Mathf.RoundToInt(value * factor);
                if (next == value) next += factor > 1f ? 1 : -1;
                field.Value = next;
            }

            field.Buffer = null;
        }

        private void ResetAll()
        {
            foreach (DevTunedField field in _fields)
            {
                if (field.Changed) field.Value = field.Original;
                field.Buffer = null;
            }

            _status = "Reset to the values when picked.";
        }

        private void ApplyToAll()
        {
            if (_target == null) return;

            var others = new List<GameObject>();
            if (_target.GetComponent<Tower>() != null)
            {
                var towers = new List<Tower>();
                Tower.GetActive(towers);
                foreach (Tower t in towers)
                {
                    if (t.name == _target.name && t.gameObject != _target) others.Add(t.gameObject);
                }
            }
            else
            {
                foreach (EnemyHealth e in FindObjectsByType<EnemyHealth>())
                {
                    if (e.name == _target.name && e.gameObject != _target) others.Add(e.gameObject);
                }
            }

            int fields = 0;
            foreach (GameObject other in others) fields += DevTuning.ApplyTo(other, _fields);
            _status = "Applied to " + others.Count + " other '" + _target.name + "' (" + fields + " values). Only objects alive now; new ones use the prefab.";
        }

        private void CopyAsText()
        {
            string text = DevTuning.AsText(_target != null ? _target.name : "(nothing)", _fields);
            GUIUtility.systemCopyBuffer = text;
            _status = "Copied the changed values to the clipboard.";
        }

        private void CopyToAsset()
        {
            if (_target == null) return;

            List<DevTunedChange> changes = DevTuning.Changes(_fields);
            GameObject hint = null;
            Tower tower = _target.GetComponent<Tower>();
            if (tower != null && _placer != null && _placer.Catalog != null)
            {
                for (int i = 0; i < _placer.Catalog.Count; i++)
                {
                    TowerData data = _placer.Catalog[i];
                    if (data != null && data.DisplayName == _target.name && data.Prefab != null) hint = data.Prefab.gameObject;
                }
            }

            _status = DevTuningWriteBack.Apply(_target, hint, changes);
        }
    }
}
#endif
